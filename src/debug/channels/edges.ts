import { createDebugChannel } from "../debug-channel";

/**
 * Канал порогов подгрузки.
 *
 * Зачем нужен: колбэк подгрузки обязан уйти один раз на вход в пороговую зону.
 * Между «пользователь у кромки» и «колбэк ушёл» стоят три независимых решения —
 * геометрия, защёлка кромки и общий гейт обеих кромок, — и каждое умеет молча
 * отменить подгрузку. Симптомы у всех трёх одинаковые: история не грузится либо
 * грузится дважды подряд.
 *
 * Канал показывает и геометрию, и то, кто именно не пропустил колбэк.
 */
export const edgesDebug = createDebugChannel(
  "edges",
  "пороги подгрузки: расстояния до кромок, защёлки и гейт",
);

/**
 * Геометрия кромок.
 *
 * Первое, что проверяют: считает ли список расстояние до кромки так же, как
 * видит пользователь. Расстояния идут в координатах контента и по его полной
 * высоте — с подвалом и распорками.
 */
export const logEdgesState = edgesDebug.event("state", {
  about: "расстояния до кромок и пороги, с которыми они сравниваются",
  // Расстояния меняются на каждом событии скролла: это непрерывная величина, и
  // её не отслеживают, а выбирают по ней момент — раз в несколько кадров.
  repeat: { everyMs: 200 },
  fields: {
    fromStart: "расстояние до начала списка, px",
    fromEnd:
      "расстояние до конца, px. Считается от низа контента, а не от последней строки",
    startAt: "порог начала в px — доля вьюпорта, развёрнутая в расстояние",
    endAt: "порог конца в px",
    shorter:
      "контент короче вьюпорта: конец достигнут по построению, порог тут ни при чём",
    skip: "колбэки подавлены: идёт свой переезд, прилипание к концу, компенсация или доводка стартовой позиции",
  },
});

/**
 * Колбэк подгрузки ушёл.
 *
 * Ровно на переходе внутрь зоны, а не на каждой проверке: событий скролла в
 * зоне десятки в секунду.
 */
export const logEdgesReached = edgesDebug.event("reached", {
  about: "кромка достигнута, колбэк отправлен",
  key: "edge",
  fields: {
    edge: "какая кромка: start (история вверх) или end (лента вниз)",
    distance: "расстояние до кромки в момент срабатывания",
    threshold: "порог, который перешли",
    allowed:
      "кромка, разблокированная текущим жестом: направление жеста решает, какая из двух имеет право сработать",
  },
});

/**
 * Вход в зону был, а колбэк не ушёл.
 *
 * Самая частая жалоба на подгрузку выглядит именно так, и на экране причина
 * неотличима: пользователь у кромки, а данных нет. Здесь речь именно о
 * неожиданном отказе — гейт не пропустил кромку, хотя пользователь у неё.
 */
export const logEdgesBlocked = edgesDebug.event("blocked", {
  about: "кромка достигнута, но гейт не пропустил колбэк",
  problem: true,
  key: "edge",
  fields: {
    edge: "какая кромка молчит",
    distance: "расстояние до неё",
    cause:
      "«гейт» — недавно сработала другая кромка, и до нового жеста эта молчит",
    allowed: "какая кромка разблокирована текущим жестом",
  },
});

/**
 * Кромка в зоне, но колбэки подавлены своим движением списка.
 *
 * Это не отказ, а порядок вещей: переезд к концу списка иначе немедленно
 * запускал бы подгрузку. Печатается редко и без пометки проблемы — нужно лишь
 * затем, чтобы молчание кромки во время своего движения не искали в другом
 * месте.
 */
export const logEdgesSuppressed = edgesDebug.event("suppressed", {
  about: "кромка в зоне, но идёт своё движение списка",
  repeat: { everyMs: 500 },
  key: "edge",
  fields: {
    edge: "какая кромка молчит",
    distance: "расстояние до неё",
    cause:
      "что именно подавляет: свой переезд, прилипание к концу, компенсация или доводка стартовой позиции",
  },
});

/**
 * Защёлка кромки сброшена — кромка снова может сработать.
 *
 * Без сброса подгрузка сверху уходит ровно один раз за всё время: она удерживает
 * позицию, поэтому расстояние до начала после неё не меняется и обычного выхода
 * за порог не происходит.
 */
export const logEdgesReset = edgesDebug.event("reset", {
  about: "кромка снова готова сработать",
  key: "edge",
  fields: {
    edge: "какая кромка снова готова",
    cause:
      "«вышли» — ушли за порог с запасом; «вырос» — контент изменился, а до кромки по-прежнему близко; «жест» — новый жест в сторону этой кромки",
    distance: "расстояние до кромки на момент сброса",
  },
});
