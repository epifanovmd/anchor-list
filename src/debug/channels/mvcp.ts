import { createDebugChannel } from "../debug-channel";

/**
 * Канал удержания видимой позиции.
 *
 * Зачем нужен: компенсация — это цепочка из четырёх величин. Якорь снимается до
 * изменения, после пересчёта смотрится, на сколько уехала его позиция, из этого
 * решается сдвиг, и сдвиг применяется к смещению. Разойтись они могут в любом
 * звене, а на экране все расхождения выглядят одинаково — строка, за которой
 * следил пользователь, уехала под пальцем.
 *
 * Канал печатает всю цепочку целиком: по строке видно не только «сдвинул на
 * столько», но и почему именно на столько и удержалась ли строка на месте.
 */
export const mvcpDebug = createDebugChannel(
  "mvcp",
  "удержание видимой позиции: якорь, сдвиг и его промах",
);

/**
 * Якорь снят.
 *
 * Снимается строго до изменения данных или размеров: позиции, снятые после,
 * относятся уже к другой раскладке, и разница по ним ничего не значит.
 */
export const logMvcpCapture = mvcpDebug.event("capture", {
  about: "якорь снят перед изменением",
  fields: {
    reason: "что вызвало: смена данных или замер строки",
    anchor: "индекс первой опоры — за неё будут держаться",
    position: "позиция якоря в координатах контента до изменения",
    offset:
      "расстояние от якоря до верхней кромки: то, что обязано сохраниться",
    candidates:
      "сколько запасных опор снято следом. Первая может не пережить изменение — тогда возьмётся следующая",
  },
});

/**
 * Сдвиг применён.
 *
 * Главная строка канала: `moved` — причина, `applied` — что из неё доехало.
 * Расхождение между ними и есть величина, на которую дёрнется картинка.
 */
export const logMvcpShift = mvcpDebug.event("shift", {
  about: "компенсация посчитана и применена",
  key: "anchor",
  fields: {
    anchor: "индекс опоры, по которой считали",
    reason: "что вызвало: данные или размер",
    candidate:
      "номер сработавшей опоры: 0 — первая видимая, больше нуля — та не пережила изменение",
    moved:
      "на сколько уехала позиция якоря, px. Это и есть сдвиг, который увидел бы пользователь без компенсации",
    applied:
      "сколько из moved доехало до смещения. Расхождение с moved — рывок на экране",
    lost: "сколько обрезала граница контента: у края списка двигать дальше некуда",
    residual:
      "остаток, отложенный до следующего прохода: сдвиги мельче кванта копятся, а не теряются",
  },
});

/**
 * Держать было не за что.
 *
 * Контент поехал без компенсации — это и есть тот случай, когда подгрузка
 * истории уводит переписку вниз.
 */
export const logMvcpNoAnchor = mvcpDebug.event("noAnchor", {
  about: "компенсация не состоялась: опоры нет",
  problem: true,
  fields: {
    reason: "что вызвало: данные или размер",
    cause:
      "«не снят» — на момент изменения якорь снять не удалось (пустой список, ничего в кадре); «не пережил» — снятые опоры исчезли из данных",
    candidates: "сколько опор было снято — все они не пережили изменение",
  },
});

/**
 * Опорная строка не удержала своё место.
 *
 * Проверяется ровно то, ради чего компенсация существует: расстояние от якоря
 * до верхней кромки до изменения и после. Разошлось — ошиблась сама
 * компенсация. Совпало, а на экране прыжок — держали не ту строку либо сдвиг не
 * доехал до нативного слоя.
 */
export const logMvcpMiss = mvcpDebug.event("miss", {
  about: "опора не осталась на месте — это и видно глазом",
  problem: true,
  key: "anchor",
  fields: {
    anchor: "индекс опоры — за эту строку держались",
    before: "расстояние от опоры до верхней кромки до изменения",
    after: "то же расстояние после",
    error: "их разница: на столько строка уехала на экране",
  },
});

/**
 * Компенсация пропущена по скорости.
 *
 * На броске замеры приходят пачками, и компенсировать каждый значит спорить с
 * инерцией нативного скролла. Пропуск — осознанный размен: сдвиг пойдёт как
 * есть, но без борьбы за смещение.
 */
export const logMvcpSkip = mvcpDebug.event("skip", {
  about: "замер не компенсируется: список идёт слишком быстро",
  fields: {
    velocity: "скорость на момент замера, px/мс",
    limit: "порог, выше которого компенсация отключается",
    key: "строка, чей замер пропущен",
  },
});
