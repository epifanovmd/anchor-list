import { createDebugChannel } from "../debug-channel";

/**
 * Канал стартовой позиции и первого показа.
 *
 * Зачем нужен: цель начального скролла считается по метрикам, а те до измерения
 * ячеек оценочные — поэтому позиция уточняется по кадрам и сдаётся либо когда
 * перестала уезжать, либо по исчерпании попыток. По экрану не сказать, чем
 * кончилось: список открылся не там потому, что цель посчиталась по оценкам,
 * или потому, что цель была верна, а увёл список кто-то следом.
 *
 * Сюда же попадает решение показать список: до измерений позиции оценочные, и
 * показанный слишком рано кадр — та самая каша при открытии.
 */
export const initialDebug = createDebugChannel(
  "initial",
  "стартовая позиция и первый показ списка",
);

/**
 * Цель ещё не вычислима.
 *
 * Элемента, к которому просили встать, ещё нет в метриках либо неизвестна
 * геометрия. Много таких строк подряд означает, что доводка ждёт данных, а не
 * промахивается.
 */
export const logInitialWait = initialDebug.event("wait", {
  about: "цель ещё не посчитать",
  fields: {
    attempt: "какая это по счёту попытка",
    target: "тип цели: index (встать на элемент) или offset",
    index: "индекс целевого элемента",
    position: "его позиция по метрикам — она и уезжает, пока строки меряются",
    size: "его размер: оценка до замера, факт после",
    viewOffset: "запрошенный отступ цели от кромки вьюпорта",
    count: "сколько элементов знает список: цели вне этого числа не существует",
    content: "высота контента, по которой обрезается запрос",
    measured:
      "замер контента пришёл. До него нативный слой разложил только начало списка и обрежет любой запрос вглубь",
    origin: "начало координат контента: на него сдвигает шапка",
    viewport: "размер вьюпорта: без него цель не посчитать вовсе",
    revision:
      "счётчик изменений раскладки. Растёт от каждого применённого замера — значит цель ещё уезжает",
  },
});

/**
 * Попытка встать на позицию.
 *
 * Проверяется прошлая команда, а не эта: нативный слой применяет смещение не в
 * вызове, и сразу после него живое значение — ещё старое.
 */
export const logInitialApply = initialDebug.event("apply", {
  about: "попытка доводки: куда просили встать и где список оказался",
  fields: {
    attempt:
      "номер попытки: их всего десять, и по нему видно, близко ли предел",
    offset: "смещение, которое просим",
    live: "живое нативное смещение на этот момент — итог прошлой попытки",
    arrived:
      "список доехал туда, куда звала прошлая попытка. «нет» — команду перебили: нативная компенсация замеров или граница контента",
    settled:
      "цель больше не уедет: всё до неё измерено. Только после этого доводка кончается",
    target: "тип цели: index (встать на элемент) или offset",
    index: "индекс целевого элемента",
    position: "его позиция по метрикам — она и уезжает, пока строки меряются",
    size: "его размер: оценка до замера, факт после",
    viewOffset: "запрошенный отступ цели от кромки вьюпорта",
    count: "сколько элементов знает список: цели вне этого числа не существует",
    content: "высота контента, по которой обрезается запрос",
    measured:
      "замер контента пришёл. До него нативный слой разложил только начало списка и обрежет любой запрос вглубь",
    origin: "начало координат контента: на него сдвигает шапка",
    viewport: "размер вьюпорта: без него цель не посчитать вовсе",
    revision:
      "счётчик изменений раскладки. Растёт от каждого применённого замера — значит цель ещё уезжает",
  },
});

/**
 * Доводка кончилась.
 *
 * `settled` — цель устоялась, позиция верна. Исчерпание попыток означает, что
 * список показан на позиции, посчитанной по оценкам.
 */
export const logInitialFinish = initialDebug.event("finish", {
  about: "доводка стартовой позиции завершена",
  fields: {
    attempts: "сколько попыток понадобилось",
    offset: "смещение, на котором остановились",
    reason:
      "«settled» — цель устоялась; всё остальное — доводка сдалась, и позиция посчитана по оценкам",
  },
});

/**
 * Замер во время доводки.
 *
 * `revealed=да` — замер пришёл уже после показа: это и есть перекладка на
 * глазах у пользователя.
 */
export const logInitialMeasure = initialDebug.event("measure", {
  about: "замер строки, меняющий стартовую цель",
  key: "index",
  fields: {
    index: "индекс измеренной строки",
    from: "чем её считали до замера — оценкой или прошлым замером",
    to: "чем она оказалась",
    revealed:
      "список уже показан. «да» означает перекладку на глазах у пользователя",
  },
});

/**
 * Список показан.
 *
 * До этого момента он скрыт: показывать раскладку по оценкам нельзя — строки с
 * непохожей высотой налезают друг на друга.
 */
export const logInitialReveal = initialDebug.event("reveal", {
  about: "список показан пользователю",
  fields: {
    attempts: "сколько попыток доводки прошло до показа",
    cause:
      "«позиция» — доводка кончилась; «замеры» — видимые строки измерены; «страховка» — измерений так и не дождались",
    rounds: "сколько кругов прождала страховка первого показа",
  },
});
