import { createDebugChannel } from "../debug-channel";

/**
 * Канал прилипания.
 *
 * Зачем нужен: прилипание считается в трёх местах сразу — ядро выбирает
 * активный якорь, привязка публикует его геометрию контейнеру, worklet считает
 * смещение на каждом кадре. Расхождение любых двух видно на экране как
 * исчезнувший или застывший якорь, но по самому экрану не сказать, какое из
 * трёх ошиблось.
 *
 * Разделы идут по этой же цепочке: `active` → `bind` → `offset`, плюс `pin` и
 * `overlay` — про копию в слое поверх контента. Последние два печатает
 * UI-поток: смещение считается там, и сверять его нужно именно с тем, что видел
 * worklet, а не с тем, что в тот же момент думал JS.
 */
export const stickyDebug = createDebugChannel(
  "sticky",
  "прилипание: выбор якоря, его геометрия и смещение на UI-потоке",
);

/**
 * Выбор активного якоря.
 *
 * Первое звено: список решил, какой элемент прилипает у этой кромки. Индекс
 * `-1` означает, что прилипать нечему — и если якорь при этом виден на экране,
 * ошибка уже здесь.
 */
export const logStickyActive = stickyDebug.event("active", {
  about: "выбран активный якорь кромки",
  // Скролл и вьюпорт нужны как контекст выбора, но сам выбор меняется редко:
  // сравнение идёт по нему.
  repeat: "changes",
  compare: ["index", "limit"],
  key: "edge",
  fields: {
    edge: "кромка: start или end",
    index: "индекс прилипшего элемента; −1 — прилипать нечему",
    limit:
      "позиция, дальше которой якорь не идёт: его выталкивает следующий якорь той же кромки",
    scroll: "смещение, на котором сделан выбор",
    viewport: "размер вьюпорта — из него считается кромка end",
  },
});

/**
 * Геометрия якоря у контейнера.
 *
 * Второе звено: то, что ядро выбрало, доехало до контейнера. Расхождение
 * `index` с `active` означает, что worklet считает смещение по чужой строке.
 */
export const logStickyBind = stickyDebug.event("bind", {
  about: "геометрия прилипшего элемента отдана контейнеру",
  repeat: "changes",
  key: "index",
  fields: {
    index: "индекс элемента",
    container: "номер контейнера, в котором он живёт",
    edge: "кромка, к которой прилипает",
    position: "позиция в координатах контента",
    size: "высота: от неё считается выталкивание следующим якорем",
    limit: "предел выталкивания, посчитанный для этого элемента",
    clipped:
      "содержимое подрезано границами строки. У прилипшего это означает обрезанный якорь на экране",
  },
});

/**
 * Копия в слое поверх контента.
 *
 * Слой нужен там, где якорь обязан лежать выше остального контента; копия
 * внутри контента в это время прячется. `rendered` = −1 при видимом `active`
 * означает, что рисовать нечем — не задан рендер копии.
 */
export const logStickyPin = stickyDebug.event("pin", {
  about: "состояние копии якоря в слое поверх контента",
  repeat: "changes",
  key: "edge",
  fields: {
    edge: "кромка, которой принадлежит слой",
    active: "какой элемент прилип по мнению ядра",
    rendered:
      "какой элемент рисует слой; −1 — не рисует. Расхождение с active — застывший якорь на экране",
    hasRenderer: "рендер копии задан. «нет» — слою нечем рисовать",
    position: "позиция элемента в контенте",
    size: "его высота: от неё считается выталкивание",
    limit: "предел выталкивания",
  },
});

/**
 * Смещение якоря на UI-потоке.
 *
 * Последнее звено: worklet каждый кадр считает, на сколько сдвинуть строку от
 * её места в контенте. Состояний три, и на экране они выглядят по-разному —
 * якорь едет с контентом, стоит у кромки или его выталкивает следующий.
 *
 * Печатает {@link ListStickyFrame}: там же, где считается смещение.
 */
export const STICKY_OFFSET_EVENT = stickyDebug.worklet("offset", {
  about: "worklet посчитал смещение прилипшей строки",
  fields: {
    state:
      "«едет» — якорь ещё идёт с контентом; «стоит» — прилип к кромке; «вытеснен» — его выталкивает следующий; «уведён» — контейнер за пределами контента и смещение не считается вовсе",
    shift: "на сколько строка сдвинута от своего места в контенте",
    position: "её место в контенте",
    edgePos:
      "где сейчас кромка в тех же координатах — с ней и сравнивается position",
    limit: "предел выталкивания",
  },
});

/**
 * Видимость копии в слое поверх контента.
 *
 * Копий две — внутри контента и в слое, — и видима всегда ровно одна. Обе
 * видимые дают двойника на экране, обе скрытые — пропавший якорь.
 */
export const STICKY_OVERLAY_EVENT = stickyDebug.worklet("overlay", {
  about: "копия якоря в слое поверх контента показана или скрыта",
  fields: {
    visible:
      "копия в слое видима. Обратное состояние — у копии внутри контента",
    shift: "сдвиг слоя по экрану",
    scroll: "смещение на UI-потоке на этот кадр",
    position: "место элемента в контенте",
    limit: "предел выталкивания",
  },
});

/**
 * Копия якоря внутри контента.
 *
 * Пока слой поверх рисует свою копию, эта прячется прозрачностью — место для
 * касаний за ней остаётся. Экранная координата печатается затем, что по ней
 * видно разрыв между копиями: если они разошлись, при переключении якорь
 * дёргается.
 */
export const STICKY_FRAME_EVENT = stickyDebug.worklet("frame", {
  about: "копия якоря внутри контента спрятана или показана",
  fields: {
    hidden: "копия внутри контента спрятана — значит рисует слой",
    layer: "какой элемент рисует слой по мнению UI-потока",
    screen:
      "экранная координата копии. Расхождение с копией в слое — тот самый рывок при переключении",
    position: "место элемента в контенте",
    limit: "предел выталкивания",
  },
});
