import { createDebugChannel } from "../debug-channel";

/**
 * Канал раскладки.
 *
 * Зачем нужен: на экране видно только результат — строка на месте или её нет, —
 * а между «список посчитал диапазон» и «строка нарисована» лежат три шага:
 * выбор диапазона по смещению, раздача контейнеров под элементы диапазона и
 * замер того, что React в них нарисовал. Пустая полоса в кадре может означать
 * ошибку любого из них, и различаются они только числами.
 *
 * Обзор канала — где список стоит и что пошло не так: `range`, `blank`,
 * `measure`, `content`. Поштучная возня с контейнерами — `bind` и `recycle` —
 * помечена подробностями и включается по имени: на прокрутке этих строк по
 * нескольку на кадр, и обзор в них тонет. Сколько их было за секунду, считает
 * замер — см. [performance.md](../../../docs/performance.md).
 */
export const layoutDebug = createDebugChannel(
  "layout",
  "раскладка: диапазон отрисовки, контейнеры, замеры, пустоты",
);

/**
 * Диапазон отрисовки сменился.
 *
 * Смонтированы только элементы из буферизованного диапазона — на этом держится
 * виртуализация. Если строка не появилась, первый вопрос: попала ли она в
 * диапазон вообще.
 */
export const logLayoutRange = layoutDebug.event("range", {
  about: "диапазон отрисовки на текущем смещении",
  // Диапазон на прокрутке сдвигается каждый кадр, и построчная летопись этого
  // движения ничего не добавляет: смотрят на неё, чтобы понять, попала ли
  // строка в отрисовку, — для этого хватает нескольких снимков в секунду.
  // Смещение и скорость печатаются как контекст, но сравнение идёт по границам:
  // иначе прореженная строка выходила бы и тогда, когда диапазон стоит.
  repeat: { everyMs: 200 },
  compare: ["visible", "buffered"],
  fields: {
    visible: "видимый диапазон «start..end»: что пересекает вьюпорт",
    buffered:
      "буферизованный диапазон: он и смонтирован. Строка вне него не нарисована — сколько её ни жди",
    scroll: "смещение, по которому считался диапазон",
    velocity:
      "скорость: по ходу движения буфер растёт на неё, и это видно по разнице границ",
    lookahead:
      "запас по скорости, px. Ноль на быстром скролле — запас снят намеренно: он перестал окупаться",
    count: "сколько элементов в буферизованном диапазоне — цена этого прохода",
  },
});

/**
 * Раздача контейнеров.
 *
 * Контейнер переживает смену элемента: меняются пропы, а поддерево остаётся.
 * Рост перепривязок при том же диапазоне — это лишняя работа React на каждый
 * кадр прокрутки.
 */
export const logLayoutBind = layoutDebug.event("bind", {
  about: "контейнеры разданы под элементы диапазона",
  detail: true,
  repeat: "changes",
  fields: {
    requests: "сколько элементов просят контейнер: диапазон плюс прилипшие",
    containers: "сколько контейнеров существует после раздачи",
    rebound: "сколько сменило элемент — их поддерево перерисуется",
    released: "сколько осталось без элемента и уведено за пределы контента",
    pinned:
      "прилипшие: их держат смонтированными и за пределами диапазона, иначе якорь исчезал бы у кромки",
    cached:
      "набор запросов повторил прошлый и пересобран не был — так выглядит проход, ничего не изменивший",
  },
});

/**
 * Замер строки.
 *
 * Исходная причина большинства сдвигов: строка меряется, когда до неё дошла
 * отрисовка, — то есть уже на ходу. Её настоящий размер расходится с оценкой, и
 * на эту разницу уезжает всё, что под ней.
 */
export const logLayoutMeasure = layoutDebug.event("measure", {
  about: "пришёл замер строки и разошёлся с тем, что список предполагал",
  key: "index",
  fields: {
    index: "индекс измеренной строки",
    from: "размер, которым список считал строку до замера (оценка или прошлый замер)",
    to: "измеренный размер",
    delta: "их разница: ровно на столько уедет весь контент ниже этой строки",
    velocity:
      "скорость на момент замера: замер на ходу и замер на стоянке видны по-разному",
    compensated:
      "сдвиг будет компенсирован. «нет» на ходу означает видимый рывок — см. mvcp·skip",
  },
});

/**
 * Незакрытая часть вьюпорта.
 *
 * Снимается до привязки контейнеров, и в этом весь смысл: после неё строки
 * привязаны к тому месту, где скролл находится сейчас, и пустоты не видно по
 * построению. На экране же нарисовано то, что закоммичено прошлым проходом.
 */
export const logLayoutBlank = layoutDebug.event("blank", {
  about: "часть вьюпорта нечем закрыть — на экране полоса",
  problem: true,
  fields: {
    stage:
      "«до» — расчёт не поспел за скроллом; «после» — строк на это место нет вовсе, и это уже не задержка",
    px: "высота незакрытой полосы",
    scroll: "смещение, на котором считали",
    buffered:
      "буферизованный диапазон на этот момент — хватало ли смонтированного",
  },
});

/**
 * Контейнер сменил элемент.
 *
 * Совпадение типа означает совпадающую структуру поддерева: React переиспользует
 * его вместо перемонтирования. Промах по типу — самая дорогая перепривязка.
 */
export const logLayoutRecycle = layoutDebug.event("recycle", {
  about: "контейнер переиспользован под другой элемент",
  detail: true,
  key: "container",
  fields: {
    container: "номер контейнера",
    from: "какой элемент занимал контейнер до этого",
    to: "какой элемент занял контейнер",
    type: "тип нового элемента",
    sameType:
      "тип совпал с прошлым. «нет» — поддерево перемонтируется целиком, это самый дорогой случай; «—» — контейнер создан только что, и переиспользовать было нечего",
  },
});

/**
 * Высота контента.
 *
 * Своя высота складывается из известных размеров, нативная приходит замером
 * `ScrollView` и отстаёт на кадр-другой. По расхождению видно, что нативная
 * раскладка ещё не догнала, — а от неё зависит граница скролла.
 *
 * Печатается только расхождение: совпавшие высоты — обычный ход дела, и строка
 * о них выходила бы на каждый замер контента, то есть каждый кадр прокрутки.
 */
export const logLayoutContent = layoutDebug.event("content", {
  about: "своя высота контента разошлась с нативной",
  fields: {
    own: "высота, посчитанная списком: элементы, шапка, подвал, распорки",
    native: "замер ScrollView",
    diff: "их разница. Устойчивое расхождение сдвигает границу скролла и обрезает переезды у конца",
    items: "вклад элементов",
    header: "вклад шапки: она же задаёт начало координат элементов",
    footer: "вклад подвала — он лежит ниже последней строки",
    spacer: "вклад распорок: нижний отступ и выравнивание короткого контента",
  },
});
