import { createDebugChannel } from "../debug-channel";

/**
 * Канал видимости элементов.
 *
 * Зачем нужен: колбэк видимости — это то, по чему сообщение отмечают
 * прочитанным и запускают видео. Его молчание на экране не видно вовсе, а
 * причин у него три: элемент не проходит порог, он ушёл раньше выдержки
 * `minimumViewTime`, или набор не изменился и уведомлять было не о чем.
 *
 * Канал печатает только переходы — набор видимых меняется реже, чем идёт
 * пересчёт.
 */
export const viewDebug = createDebugChannel(
  "view",
  "видимость элементов: кто вошёл в кадр, кто вышел и что дошло до колбэка",
);

/**
 * Набор видимых изменился, колбэк вызван.
 *
 * Только изменения, а не состояние: сам пересчёт идёт при каждом сдвиге
 * диапазона, наружу же уходит лишь то, что стало другим.
 */
export const logViewChanged = viewDebug.event("changed", {
  about: "набор видимых элементов изменился и ушёл в колбэк",
  key: "pair",
  fields: {
    pair: "номер пары «условие — колбэк»: один элемент бывает видим по одному порогу и невидим по другому",
    entered: "ключи, вошедшие в кадр",
    exited: "ключи, вышедшие из кадра",
    viewable: "сколько элементов считается видимыми после изменения",
  },
});

/**
 * Элемент ждёт выдержки.
 *
 * `minimumViewTime` отсекает мелькнувшее при быстром скролле: до истечения
 * выдержки о таком элементе никто не знает.
 */
export const logViewHold = viewDebug.event("hold", {
  about: "элемент в кадре, но ждёт выдержки minimumViewTime",
  key: "key",
  fields: {
    key: "ключ элемента, о котором речь",
    pair: "номер пары «условие — колбэк»",
    waitMs: "сколько ему ждать до уведомления",
  },
});

/**
 * Элемент ушёл раньше выдержки.
 *
 * Колбэка о нём не будет вовсе — и это законно. Строка нужна, чтобы отличить
 * этот случай от порога, который элемент не прошёл.
 */
export const logViewDrop = viewDebug.event("drop", {
  about: "элемент ушёл из кадра до истечения выдержки — уведомления не будет",
  key: "key",
  fields: {
    key: "ключ элемента, о котором речь",
    pair: "номер пары «условие — колбэк»",
  },
});
