import { createDebugChannel } from "../debug-channel";

/**
 * Канал нижнего отступа.
 *
 * Зачем нужен: клавиатура едет кадрами, и на каждом кадре список обязан отдать
 * место под неё — распоркой в конце контента — и на столько же поднять
 * смещение, чтобы переписка не ушла под панель ввода. Обе величины считаются на
 * UI-потоке, а применяет их нативная раскладка кадром позже: список просит
 * сдвиг под распорку, которой в нативном дереве ещё нет, и тот обрезается
 * границей скролла.
 *
 * На экране это выглядит как контент, отстающий от клавиатуры или не доезжающий
 * до конца. Различаются случаи только числами: что просили, что подтвердил
 * нативный слой и сколько места было на тот момент.
 *
 * Печатает UI-поток — там же, где всё это считается.
 */
export const insetsDebug = createDebugChannel(
  "insets",
  "нижний отступ: распорка, выравнивание и подъём смещения под клавиатуру",
);

/**
 * Кадр хода отступа.
 *
 * Одна строка на кадр клавиатуры: из чего сложился сдвиг и попросили ли его.
 */
export const INSETS_FRAME_EVENT = insetsDebug.worklet("frame", {
  about:
    "кадр хода нижнего отступа: распорка, выравнивание, запрошенное смещение",
  fields: {
    inset:
      "нижний отступ на этом кадре — сколько низа вьюпорта занято не списком",
    delta:
      "на сколько отступ изменился с прошлого кадра. Ноль означает, что кадр пришёл не от клавиатуры, и смещение трогать нельзя",
    spacer:
      "высота распорки в конце контента: отступ плюс запас на ход раскладки. Запас лежит ниже последней строки и не виден",
    align: "сдвиг слоя контейнеров вниз: прижимает короткий контент к концу",
    from: "смещение, от которого считали: своё накопленное или живое нативное",
    to: "смещение, которое просим у нативного скролла",
    owned:
      "позицией распоряжается жест — палец на экране или инерция. Тогда накопленное смещение к ней не относится",
    revealed:
      "список уже показан. «нет» — смещение принадлежит доводке стартовой позиции, и отступ его не трогает: держать до первого показа нечего",
  },
});

/**
 * Добор остатка после того, как нативная раскладка догнала распорку.
 *
 * Нативный слой обрезает запрошенное смещение по той высоте контента, которую
 * знает сам. Остаток добирается на замере контента — когда место уже появилось.
 */
export const INSETS_SETTLE_EVENT = insetsDebug.worklet("settle", {
  about: "повторный запрос смещения после замера контента",
  fields: {
    desired: "смещение, на котором список настаивает",
    live: "живое нативное смещение: разница с desired — то, что было обрезано",
    content: "замеренная высота контента",
    room: "сколько места есть под запрошенное смещение (content − вьюпорт). Меньше desired — места ещё нет, и повторять рано",
    applied: "запрос повторён на этом кадре",
  },
});
