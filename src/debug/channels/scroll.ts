import { createDebugChannel } from "../debug-channel";

/**
 * Канал движения смещения.
 *
 * Зачем нужен: у списка три представления о том, где он стоит, — нативное
 * смещение `ScrollView`, значение, пришедшее событием, и то, каким список
 * считает скролл после компенсации. Совпадать они обязаны, а расходятся тихо:
 * на экране это выглядит рывком, отставшей картинкой или прокруткой, «липнущей»
 * к чужой позиции, — и по самому экрану не сказать, какое из трёх ошиблось.
 *
 * Здесь же видно, чьё это движение: программный переезд прыгает на тысячи точек
 * за событие, и посчитанная по нему скорость решает за список сразу два
 * вопроса — раздувать ли запас отрисовки и компенсировать ли замеры.
 */
export const scrollDebug = createDebugChannel(
  "scroll",
  "движение смещения: события скролла, скорость, свои переезды",
);

/**
 * Ход смещения по событиям.
 *
 * На ровной прокрутке дельты соседних событий близки: по ним видно частоту
 * событий, скорость и то, отстаёт ли представление списка от нативного слоя.
 */
export const logScrollEvent = scrollDebug.event("event", {
  about: "событие скролла: где список и насколько сдвинулся",
  repeat: { everyMs: 100 },
  fields: {
    offset: "смещение из события, px. То, от чего считается вся раскладка",
    delta:
      "сдвиг с прошлого события. На ровной прокрутке дельты соседних событий близки",
    velocity:
      "скорость, px/мс. По ней решается запас отрисовки и пропуск компенсации",
    native:
      "живое нативное смещение на момент обработки; расходится с offset, пока событие идёт через мост",
    lag: "|native − offset|: насколько представление списка отстало от нативного слоя. Растущий лаг — причина пустот в кадре",
    own: "движение собственное (scrollTo, доводка), а не пальцем. Своё не считается скоростью пользователя",
  },
});

/**
 * Рывок: дельта, выпавшая из ряда.
 *
 * Событие ищется в логе первым: рывок — это то же, что видно глазом, и по
 * соседним строкам других каналов сразу видно, что его вызвало — замер строки,
 * компенсация или свой переезд.
 */
export const logScrollJump = scrollDebug.event("jump", {
  about: "дельта события выпала из ряда — на экране это рывок",
  problem: true,
  fields: {
    offset: "смещение, на котором случился рывок",
    delta: "сдвиг за это событие",
    usual: "обычный сдвиг соседних событий — с чем сравнивалось",
    velocity: "скорость на этот момент: у броска большие дельты законны",
    own: "своё движение: у программного переезда рывок ожидаем и не значит ошибки",
  },
});

/**
 * Событие, отброшенное как устаревшее.
 *
 * Событие отправлено до того, как применилась компенсация: принять его — значит
 * откатить только что сделанный сдвиг, то есть вернуть на экран ровно тот
 * прыжок, ради которого компенсация и делалась.
 */
export const logScrollStale = scrollDebug.event("stale", {
  about: "событие устарело: отправлено до применения компенсации",
  fields: {
    offset: "смещение из отброшенного события",
    current: "смещение, каким список считает скролл сейчас",
  },
});

/**
 * Свой переезд.
 *
 * Пока он идёт, пороги кромок не проверяются, а скорость не считается: иначе
 * переезд к концу списка немедленно запускает подгрузку.
 */
export const logScrollProgram = scrollDebug.event("program", {
  about: "программный переезд: список двигает сам себя",
  fields: {
    target: "куда: смещение в координатах контента или «конец»",
    from: "смещение на момент команды — вместе с target даёт длину прыжка",
    animated: "с анимацией: такая команда кончается не сразу, а по затишью",
    reason:
      "чем вызван: вызов из приложения, доводка стартовой позиции, прилипание к концу",
  },
});

/**
 * Прилипание к концу списка.
 *
 * Решение принимается по состоянию **до** изменения: добавленная снизу строка
 * сама уводит список от конца, и флаг, прочитанный после неё, отвечает уже на
 * другой вопрос.
 */
export const logScrollAtEnd = scrollDebug.event("atEnd", {
  about: "прилипание к концу: запрошено, отменено или выполнено",
  fields: {
    phase:
      "запрошено (ждём кадр) · отменено (пользователь увёл список) · выполнено",
    wasAtEnd:
      "список был у конца до изменения. Именно «был»: после добавления строки флаг уже другой",
    offset: "смещение на момент запроса",
    drift:
      "на сколько смещение ушло за кадр ожидания. Больше единицы — двигал пользователь, и прилипание отменяется",
    queued: "запрос пришёл во время другого прилипания и ждёт его конца",
  },
});

/**
 * Скролл остановился.
 *
 * Момент важен для раскладки: у стоящего списка снимается запас подрезки, и
 * ровно с этого события меняется то, как контейнеры обрезают содержимое.
 */
export const logScrollRest = scrollDebug.event("rest", {
  about: "движение кончилось: скорость обнулена",
  fields: {
    offset: "где список остановился",
    velocity: "последняя посчитанная скорость перед обнулением",
  },
});
