/**
 * Формат строки лога — общий для всех каналов.
 *
 * Зачем один на всех: разбор идёт по нескольким каналам сразу — замер строки
 * из `layout`, компенсация из `mvcp` и событие скролла из `scroll` описывают
 * один и тот же кадр с трёх сторон. Сложить их в общую картину можно, только
 * если у строк одинаковые колонки и одна шкала времени.
 *
 * Строка выглядит так:
 *
 * ```
 * [mvcp·shift]        2.416 42    reason=данные moved=+18 applied=+18 lost=0
 * [mvcp·miss]!        2.418 42    before=120 after=138 error=18
 * ```
 *
 * - `[канал·событие]` — тот же ключ в скобках, что и у замера
 *   (`[list·метка]`): по нему строка опознаётся среди чужого вывода, а лог
 *   фильтруется по каналу целиком;
 * - `!` сразу за скобкой — у события есть признак проблемы: печатается только
 *   тогда, когда механика не сделала того, ради чего существует;
 * - число — секунды от включения диагностики: общая шкала всех каналов;
 * - ключ — за чем наблюдаем: индекс строки, кромка, номер контейнера. По нему
 *   же отсекаются повторы;
 * - дальше пары «величина=значение» в порядке объявления события.
 */

/**
 * Ширина колонки `[канал·событие]`: по ней строки выстраиваются в столбик.
 *
 * Считана по самому длинному имени вместе с меткой проблемы. Замер выравнивает
 * свои разделы так же — фиксированной колонкой имени: разбор идёт по числам, а
 * их не сравнить, пока они стоят в разных местах строки.
 */
const NAME_WIDTH = 20;

/** Ширина колонки ключа. */
const KEY_WIDTH = 5;

/**
 * Значение в строке лога.
 *
 * `undefined` печатается прочерком намеренно: «величины нет» — это диагноз, а
 * не пропуск. Якорь без индекса означает, что держать было не за что, и такую
 * строку нельзя отличить от пропущенной колонки. Пустая строка — то же самое:
 * тип элемента по умолчанию пуст, и колонка `type=` без значения читалась бы
 * как обрыв строки.
 */
export const formatDebugValue = (value: unknown): string => {
  "worklet";

  if (value === undefined || value === null || value === "") return "—";
  if (typeof value === "boolean") return value ? "да" : "нет";

  if (typeof value === "number") {
    if (!Number.isFinite(value)) return String(value);

    return Number.isInteger(value) ? String(value) : value.toFixed(1);
  }

  if (Array.isArray(value)) {
    return value.length === 0 ? "—" : value.map(formatDebugValue).join(",");
  }

  return String(value);
};

/**
 * Число со знаком.
 *
 * Нужно там, где величина — это изменение: «уехал на 18» и «уехал на −18» —
 * разные стороны экрана, а без знака они выглядят одинаково.
 */
export const signed = (value: number | undefined): string => {
  "worklet";

  if (value === undefined) return "—";

  const text = formatDebugValue(Math.abs(value));

  return value < 0 ? `-${text}` : `+${text}`;
};

/** Пары «величина=значение» в порядке объявления события. */
export const formatDebugValues = (values: Record<string, unknown>): string => {
  "worklet";

  let line = "";

  for (const name of Object.keys(values)) {
    line += `${line ? " " : ""}${name}=${formatDebugValue(values[name])}`;
  }

  return line;
};

/** Из чего складывается строка лога. */
export interface IDebugLineParams {
  /** Секунды от включения диагностики — общая шкала всех каналов. */
  elapsed: number;
  channel: string;
  event: string;
  /** За чем наблюдаем; пустая строка — наблюдение одно на весь список. */
  key: string;
  /** Событие говорит о том, что механика не сработала. */
  problem: boolean;
  /** Уже собранные пары «величина=значение». */
  values: string;
}

/**
 * Готовая строка лога.
 *
 * Помечена worklet-ом: те же строки печатает UI-поток — прилипание и нижний
 * отступ считаются там, — и формат обязан совпадать до колонки, иначе логи
 * двух потоков не сведутся в один разбор.
 */
export const formatDebugLine = ({
  elapsed,
  channel,
  event,
  key,
  problem,
  values,
}: IDebugLineParams): string => {
  "worklet";

  // Метка проблемы стоит вплотную к скобке, а не отдельной колонкой: так она
  // читается частью имени события и не разрывает выравнивание остальных.
  const name = `[${channel}·${event}]${problem ? "!" : ""}`.padEnd(NAME_WIDTH);
  const time = elapsed.toFixed(3).padStart(8);

  return `${name}${time} ${key.padEnd(KEY_WIDTH)} ${values}`;
};
