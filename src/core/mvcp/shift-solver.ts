/**
 * Минимальный сдвиг, который вообще доходит до нативного слоя.
 *
 * iOS отбрасывает смещение кадра меньше 0.5pt, Android считает его в целых
 * пикселях. Поэтому компенсация применяется целыми точками, а остаток меньше
 * точки копится до следующего прохода.
 */
export const MIN_SHIFT = 1;

/** Исходные данные для расчёта компенсирующего сдвига. */
export interface IShiftInput {
  /** Смещение скролла, каким его считает список. */
  scroll: number;
  /** На сколько уехал якорь: разница его позиций до и после изменения. */
  moved: number;
  /** Недоведённая доля точки с прошлого прохода. */
  residual: number;
  /** Полная высота контента ScrollView, включая шапку, подвал и распорки. */
  contentSize: number;
  scrollLength: number;
}

/** Разобранный по частям сдвиг: что уйдёт в нативный слой, что потеряно. */
export interface IShiftSolution {
  /** Сколько нужно сдвинуть, с учётом накопленного остатка. */
  wanted: number;
  /** Граница скролла у нового контента. */
  maxScroll: number;
  /** Смещение после того, как ScrollView сам подтянул его к границе. */
  settled: number;
  /** Куда нужно прийти. */
  target: number;
  /** Целый сдвиг, который уйдёт в нативный слой. */
  applied: number;
  /** Остаток меньше точки, переносимый на следующий проход. */
  residual: number;
  /** Насколько ScrollView подтянул смещение сам. */
  pulledByScrollView: number;
  /** Сколько сдвига потеряно на упоре в границы контента. */
  lost: number;
}

/**
 * Величина компенсирующего сдвига.
 *
 * Зачем нужна: якорь уехал на `moved` — значит ровно на столько же нужно
 * подвинуть скролл, чтобы строка осталась на своём месте экрана. Всё остальное
 * здесь — поправки, каждая из которых была отдельным багом.
 *
 * Какие проблемы решает:
 * - **двойная компенсация у конца списка.** Когда контент стал короче,
 *   ScrollView сам подтягивает смещение к новой границе — у конца списка
 *   удаление сверху уже сдвинуло скролл ровно на высоту удалённого. Считать эту
 *   часть своей значит сделать её дважды, и экран уезжает вдвое;
 * - **упор в границы.** Опустить якорь на прежнюю строку экрана бывает нечем —
 *   контента под ним не хватает. Сдвиг обрезается по границе, а накопленный
 *   остаток при этом сбрасывается: доводить у границы уже нечего;
 * - **потеря долей пикселя.** Нативный слой принимает только целые точки, а
 *   строки растут на дробные величины. Без накопления остатка каждый такой рост
 *   молча терялся бы, и за десяток обновлений экран уезжал на заметную величину.
 */
export const solveShift = ({
  scroll,
  moved,
  residual,
  contentSize,
  scrollLength,
}: IShiftInput): IShiftSolution => {
  const wanted = moved + residual;
  const maxScroll = Math.max(0, contentSize - scrollLength);
  const settled = Math.min(scroll, maxScroll);
  const target = Math.min(Math.max(0, scroll + wanted), maxScroll);
  const exact = target - settled;
  const applied = Math.round(exact);
  const clamped = target !== scroll + wanted;

  return {
    wanted,
    maxScroll,
    settled,
    target,
    applied,
    // Долю точки копим, только когда сдвиг прошёл целиком: у границы контента
    // доводить уже нечего.
    residual: clamped ? 0 : exact - applied,
    pulledByScrollView: settled - scroll,
    lost: scroll + wanted - target,
  };
};
