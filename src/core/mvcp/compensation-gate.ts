/**
 * Скорость, выше которой удержание позиции по размеру не окупается, —
 * в экранах за миллисекунду.
 *
 * Смысл величины: за сколько времени вьюпорт сменяется целиком. Порог отвечает
 * примерно тридцати миллисекундам, то есть двум кадрам. Медленнее — строка,
 * ради которой делается сдвиг, остаётся на экране, и её рывок пользователь
 * видит; быстрее — её уносит раньше, чем сдвиг доедет до кадра.
 *
 * Замеры на устройстве: чтение пальцем идёт на 0.002–0.006 экрана/мс и там
 * компенсация двигает картинку на десятки пикселей — она нужна. На броске
 * скорость держится около 0.06 экрана/мс, а средний сдвиг падает до четырёх
 * пикселей: якорь уже не тот, на который смотрел пользователь, и компенсация
 * возит содержимое впустую. Порог взят между этими двумя режимами, на порядок
 * выше чтения и вдвое ниже броска.
 */
const COMPENSATION_SCREENS_PER_MS = 0.03;

/**
 * Список идёт слишком быстро, чтобы удержание позиции имело смысл.
 *
 * Зачем нужно: каждый замер строки в неизмеренной территории снимает якорь, а
 * каждый снятый якорь стоит flush-у двух полных привязок вместо одной плюс
 * нативной подстройки скролла. На броске таких замеров сотни, и все они платят
 * за сдвиг, которого никто не увидит.
 *
 * Спрашивать это нужно **до** применения замера. После него контент уже вырос,
 * и ответ будет уже про другое состояние списка.
 */
export const isPastCompensationSpeed = (
  velocity: number,
  scrollLength: number,
): boolean =>
  scrollLength > 0 &&
  Math.abs(velocity) > scrollLength * COMPENSATION_SCREENS_PER_MS;
