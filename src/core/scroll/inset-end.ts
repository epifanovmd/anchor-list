/**
 * На сколько кадров распорка держится впереди отступа.
 *
 * Высота распорки едет через дерево раскладки и применяется уже после того, как
 * в этом же кадре отработал `scrollTo`. Значит граница скролла на момент запроса
 * — прежняя, и у самого низа списка, где смещение стоит ровно на ней, запрос
 * обрезается: контент отстаёт от клавиатуры на кадр. Запас впереди убирает
 * обрез; он весь ниже последней строки и не виден, а как только движение
 * кончилось — сходит в ноль вместе с дельтой.
 *
 * Два, а не один: в начале хода клавиатура разгоняется, и следующая дельта
 * больше предыдущей.
 */
const SPACER_LEAD_FRAMES = 2;

/**
 * Порог шума при сравнении своих величин с нативными, px.
 *
 * Список считает низ в точках с дробями, а обратно смещение приходит от
 * нативного скролла квантованным — на экране 3× это трети точки, — да ещё и
 * после округления раскладки. Строгое сравнение с такими числами не сходится
 * никогда: «дошло ли смещение туда, куда просили» не выполнится ни разу, а
 * движением будет считаться дрожь производного значения в тысячные доли.
 *
 * Полточки: больше одного нативного кванта и меньше того, что видно глазом.
 */
export const INSET_END_EPSILON = 0.5;

/**
 * Насколько близко к концу контента смещение считается стоящим на кромке, px.
 *
 * Тот же шум, что и в {@link INSET_END_EPSILON}, плюс расхождение своей высоты
 * контента с нативной: список складывает её из собственных размеров, а Yoga
 * округляет раскладку по сетке пикселей. Допуск поэтому больше кванта в разы.
 *
 * Ошибиться здесь дороже, чем в остальных сравнениях: не узнать низ — значит
 * складывать дельты на этих же долях, и за несколько открытий клавиатуры
 * контент отползает от кромки на видимый зазор.
 */
const AT_END_TOLERANCE = 2;

/** Из чего складывается низ списка на этом кадре. */
export interface IInsetEndParams {
  /** Смещение скролла, от которого считаем. */
  scroll: number;
  /** Нижний отступ на прошлом кадре. */
  previousInset: number;
  /** Нижний отступ прямо сейчас. */
  insetEnd: number;
  /**
   * Высота контента без нижнего отступа и без сдвига выравнивания: элементы,
   * шапка, подвал и распорка у конца.
   *
   * Считается по размерам, которые список знает сам, а не по замеру
   * `contentSize`: замер приходит через JS и отстаёт на кадр-другой, а на ходу
   * клавиатуры это ровно та величина, по которой решается, докуда двигать
   * контент. По отставшему замеру диапазон выходит короче настоящего, сдвиг
   * обрезается — и контент остаётся ниже, чем должен.
   */
  baseHeight: number;
  /** Размер вьюпорта вдоль оси скролла. */
  scrollLength: number;
  /** Короткий контент прижимается к концу. */
  alignItemsAtEnd: boolean;
}

/** Как низ списка разложен на этом кадре. */
export interface IInsetEndLayout {
  /**
   * Сдвиг слоя контейнеров вниз, прижимающий короткий контент к концу.
   *
   * Трансформ, а не отступ в раскладке: высота контента от него не меняется,
   * поэтому короткий список остаётся непрокручиваемым — прокручивать в нём
   * нечего.
   */
  alignOffset: number;
  /** Куда обязано встать смещение скролла. */
  scroll: number;
  /**
   * Высота распорки в конце контента: отступ плюс запас на ход раскладки.
   *
   * В расчёт запас не входит — ни в выравнивание, ни в границу скролла: место
   * под ним нужно нативному слою, а не списку. См. {@link SPACER_LEAD_FRAMES}.
   */
  spacer: number;
}

/**
 * Раскладка низа списка под нижний отступ.
 *
 * Worklet: считается на UI-потоке в такт клавиатуре. Через JS раскладка
 * отставала бы на кадр, и это видно рывком.
 *
 * Правило одно: **низ контента стоит на верхней кромке того, что занимает низ
 * вьюпорта.** То есть видимое над этой кромкой остаётся видимым при любом
 * изменении отступа.
 *
 * Держат это правило двое, и на каждом кадре они делят подъём между собой:
 *
 * - пока контента меньше экрана, поднимает **сдвиг выравнивания** — в
 *   непрокручиваемом списке скроллу двигать нечем;
 * - когда больше — **смещение скролла**: место ему даёт распорка отступа в
 *   конце контента;
 * - на границе сдвиг доезжает до нуля, остаток добирает скролл.
 *
 * Сколько подъёма забрал сдвиг, отдельно считать не нужно: пока он больше нуля,
 * контент короче экрана, а значит граница скролла — ноль. Дальше граница растёт
 * ровно на ту часть отступа, которую сдвигу уже нечем закрыть, и зажим по ней
 * сам оставляет скроллу его половину подъёма.
 *
 * Смещение двигается только от изменения отступа. Выравнивание меняется и от
 * прихода новых строк, но тот подъём — не наше дело: им занимаются удержание
 * позиции и прилипание к концу, а вмешаться сюда значило бы увести список от
 * каждого нового сообщения.
 */
export const resolveInsetEnd = ({
  scroll,
  previousInset,
  insetEnd,
  baseHeight,
  scrollLength,
  alignItemsAtEnd,
}: IInsetEndParams): IInsetEndLayout => {
  "worklet";

  const insetDelta = insetEnd - previousInset;
  const contentHeight = baseHeight + insetEnd;
  const previousMaxScroll = Math.max(
    0,
    baseHeight + previousInset - scrollLength,
  );
  const alignOffset = alignItemsAtEnd
    ? Math.max(0, scrollLength - contentHeight)
    : 0;
  const maxScroll = Math.max(0, contentHeight - scrollLength);
  // Низ контента стоял на кромке — там и остаётся, без сложения дельт. Иначе
  // доли, теряемые на округлении смещения, копятся из хода в ход и уводят его
  // от кромки; на открытии это прячет зажим по границе, а на закрытии
  // зажимать нечего, и зазор остаётся.
  const shifted =
    scroll >= previousMaxScroll - AT_END_TOLERANCE
      ? maxScroll
      : scroll + insetDelta;
  // Пока подъём делает сдвиг, скролл не при чём — и запас ему не нужен: он
  // только сделал бы непрокручиваемый список прокручиваемым на время хода.
  const lead =
    alignOffset > 0 ? 0 : Math.max(0, insetDelta) * SPACER_LEAD_FRAMES;

  return {
    alignOffset,
    scroll: Math.min(Math.max(shifted, 0), maxScroll),
    spacer: insetEnd + lead,
  };
};
