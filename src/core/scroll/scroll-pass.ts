/** Бюджет кадра, мс. */
const FRAME_MS = 16;

/**
 * Был ли пересчёт настолько недавно, что он из того же кадра.
 *
 * Зачем нужно: отложенный проход, у которого в этом кадре уже применились
 * замеры, повторил бы ту же работу — применение посчитано по живому смещению.
 *
 * Для решения «отложить ли событие скролла» не годится: там граница — сам кадр,
 * а не время. Проход начала кадра идёт по смещению, которое скролл уже покинул,
 * и событие, пришедшее через пару миллисекунд, по времени выглядело бы
 * повтором, хотя несёт новое смещение.
 */
export const shouldDeferScrollPass = (sinceLastPassMs: number): boolean =>
  sinceLastPassMs < FRAME_MS;
