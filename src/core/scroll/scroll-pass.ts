/** Бюджет кадра, мс. */
const FRAME_MS = 16;

/**
 * Отложить ли пересчёт до следующего кадра.
 *
 * Зачем нужно: нативный слой шлёт события скролла чаще, чем JS успевает
 * отрисовать кадр, — на 120-герцевом экране это два события на кадр. Проход по
 * каждому из них считает раскладку и перерисовывает строки, но на экран попадает
 * только последнее состояние кадра: вся работа предпоследнего прохода
 * выбрасывается.
 *
 * Какую проблему решает: удвоенную работу на быстром скролле. Первый проход
 * кадра идёт сразу — задержки не появляется, — а всё, что пришло следом,
 * сливается в один отложенный проход по свежему смещению.
 */
export const shouldDeferScrollPass = (sinceLastPassMs: number): boolean =>
  sinceLastPassMs < FRAME_MS;
