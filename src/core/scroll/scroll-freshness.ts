/** Смещения, между которыми выбирается то, по которому считать раскладку. */
export interface IFreshOffsetParams {
  /** Смещение из события скролла — на момент его отправки. */
  offset: number;
  /** Смещение на UI-потоке сейчас; undefined — адаптер его не отдаёт. */
  live: number | undefined;
  /**
   * Смещение **предыдущего события**, а не то, на котором список стоит.
   *
   * Направление считается по потоку событий намеренно: применённое смещение
   * могло быть подменено живым, и тогда следующее событие выглядело бы
   * движением назад. Признак направления переворачивался бы через событие, а
   * вместе с ним — и результат подмены: список метался бы между устаревшим
   * событием и живым смещением, перепривязывая контейнеры на каждом проходе.
   */
  previous: number;
  scrollLength: number;
}

/**
 * Доля вьюпорта, после которой событие считается устаревшим.
 *
 * Полэкрана — это уже другой кадр: раскладка, посчитанная по такому смещению,
 * встанет туда, откуда скролл давно ушёл.
 */
const STALE_SCREENS = 0.5;

/**
 * Смещение, по которому считать раскладку.
 *
 * Зачем нужно: пока идёт проход — привязка контейнеров и рендер строк, — скролл
 * продолжает ехать. На быстром скрабе за один проход контент уходит на десяток
 * экранов, и смещение из события к моменту обработки описывает позицию, которой
 * на экране давно нет: строки монтируются туда, где пользователя уже нет, а там,
 * где он есть, остаётся пустота.
 *
 * Подмена включается только на большом расхождении и только вперёд по ходу
 * движения. Живое смещение — единственное, о свежести чего известно наверняка;
 * прыжок против направления события означал бы, что устарело как раз оно, и
 * список откатился бы назад по собственному скроллу.
 */
export const resolveFreshOffset = ({
  offset,
  live,
  previous,
  scrollLength,
}: IFreshOffsetParams): number => {
  if (live === undefined || scrollLength <= 0) return offset;
  if (Math.abs(live - offset) <= scrollLength * STALE_SCREENS) return offset;

  const moving = Math.sign(offset - previous);

  return moving !== 0 && Math.sign(live - offset) === moving ? live : offset;
};
