import type { AnchorListStickyEdge } from "../../types";

/**
 * Куда уводится строка, ожидающая первого измерения.
 *
 * Места в раскладке она не занимает, но отрисоваться обязана — и обязательно в
 * натуральную величину: подрезанный контейнер отдаёт высоту подрезки, а не
 * содержимого. Поэтому не подрезаем, а уводим выше начала контента: туда скролл
 * не доходит, а раскладка идёт своим чередом.
 */
export const MEASURE_OFFSCREEN = -100000;

/**
 * Округление раскладки перед записью в сигналы.
 *
 * Префиксные суммы пересчитываются с разного «грязного» индекса и дают
 * результат, различающийся в последних битах float. Стор сравнивает значения,
 * и такая разница заставляла перерисовываться каждый контейнер на каждом
 * измерении — при том, что на экране не двигалось ничего.
 */
export const roundLayout = (value: number): number =>
  Math.round(value * 100) / 100;

/** Что известно о строке к моменту раскладки её контейнера. */
export interface IContainerPlacementParams {
  /** Элемент ждёт первого измерения и места в раскладке не занимает. */
  pending: boolean;
  /** Кромка прилипания; null — обычный элемент. */
  stickyEdge: AnchorListStickyEdge | null;
  /** Позиция по метрикам, до округления. */
  position: number;
  /** Размер по метрикам, до округления. */
  size: number;
  viewportTop: number;
  viewportEnd: number;
}

/** Куда встаёт контейнер и нужно ли подрезать его содержимое. */
export interface IContainerPlacement {
  position: number;
  size: number;
  /** Содержимое подрезается по отведённой высоте. */
  clipped: boolean;
}

/**
 * Где и как рисуется контейнер.
 *
 * Настоящая высота строки известна только после отрисовки. До неё в метриках
 * лежит оценка, а у строки со сменившимся содержимым — прежний размер: и то и
 * другое расходится с тем, чем строка нарисуется. Ровно на этот кадр она
 * занимает не своё место и налезает на соседей — вставленная сверху пятёрка или
 * строка, выросшая за пределами вида, своим низом въезжает в кадр поверх
 * видимых.
 *
 * Правила подрезки, каждое из которых закрывает свой случай:
 * - **строка вне вида подрезается** по отведённому месту: показывать там нечего,
 *   а въехать в кадр она больше не может. Подтверждён размер или нет — неважно,
 *   устареть может и подтверждённый;
 * - **строка в кадре не подрезается никогда**: обрезанное содержимое заметнее
 *   любого наползания, а тень или выступающий элемент рисуются за её границами
 *   законно;
 * - **прилипающие исключены целиком** — они за своими границами и живут: аватар
 *   группы держится у кромки, когда сама группа уже ушла вверх;
 * - **ожидающий измерения уводится за пределы контента** вместо подрезки:
 *   подрезанный контейнер отдал бы высоту подрезки, и элемент навсегда остался
 *   бы нулевым.
 */
export const resolveContainerPlacement = ({
  pending,
  stickyEdge,
  position,
  size,
  viewportTop,
  viewportEnd,
}: IContainerPlacementParams): IContainerPlacement => {
  const resolvedPosition = pending ? MEASURE_OFFSCREEN : roundLayout(position);
  const resolvedSize = roundLayout(size);
  const outOfView =
    resolvedPosition + resolvedSize <= viewportTop ||
    resolvedPosition >= viewportEnd;

  return {
    position: resolvedPosition,
    size: resolvedSize,
    clipped: !pending && stickyEdge === null && outOfView,
  };
};
