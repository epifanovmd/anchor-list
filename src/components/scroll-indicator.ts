/** Инсеты индикатора скролла; сторону задаёт ось, остальные список не трогает. */
export interface IScrollIndicatorInsets {
  top: number;
  left: number;
  bottom: number;
  right: number;
}

/**
 * Отступ индикатора скролла под распорку у конечной кромки контента.
 *
 * Зачем нужен: место под панелью ввода списку отдаёт распорка в подвале — она
 * часть контента, и об этом знает только контент. Индикатор скролла живёт в
 * координатах самого `ScrollView` и о распорке не догадывается: он доходит до
 * кромки экрана, тогда как контент останавливается над панелью.
 *
 * Какую проблему решает: сводит оба отступа к одному числу. Значение — та же
 * длина распорки, поэтому индикатор и контент кончаются на одной линии при
 * любой высоте панели и в любой фазе анимации клавиатуры.
 *
 * Сторону выбирает ось: у вертикального списка индикатор идёт вдоль правого
 * края и упирается вниз, у горизонтального — вдоль нижнего и упирается вправо.
 *
 * Worklet: считается на UI-потоке, в такт с распоркой.
 */
export const getScrollIndicatorInsets = (
  inset: number,
  horizontal: boolean,
): IScrollIndicatorInsets => {
  "worklet";

  const value = Math.max(0, inset);

  return horizontal
    ? { top: 0, left: 0, bottom: 0, right: value }
    : { top: 0, left: 0, bottom: value, right: 0 };
};
