/**
 * Ниже этого расхождения высоты считаются одинаковыми, px.
 *
 * Замер приходит дробным, и субпиксельная разница раскладку не двигает —
 * реагировать на неё значит платить обращением в нативный слой за ничто.
 */
const SAME_HEIGHT_EPS = 0.5;

/**
 * Нужен ли замер по событию раскладки.
 *
 * Зачем нужен: после перепривязки контейнер меряется из layout-эффекта, а следом
 * приходит `onLayout` с той же самой высотой. Такой замер ничего не уточняет,
 * но стоит обращения в нативный слой — а на быстром скролле их сотни в секунду.
 *
 * @param height высота из события раскладки.
 * @param lastMeasured последняя высота, которую вернул замер этой ячейки.
 */
export const shouldMeasureOnLayout = (
  height: number,
  lastMeasured: number | undefined,
): boolean =>
  lastMeasured === undefined ||
  Math.abs(height - lastMeasured) > SAME_HEIGHT_EPS;

/** Что изменилось у ячейки к моменту привязки контейнера. */
export interface IMeasureOnBindParams {
  /** Контейнер встал под другой элемент. */
  keyChanged: boolean;
  /** У того же элемента сменились данные — содержимое перерисовано. */
  dataChanged: boolean;
  /** Размер этого элемента список уже знает точно. */
  hasKnownSize: boolean;
}

/**
 * Нужен ли замер после привязки контейнера к элементу.
 *
 * Зачем нужен: на быстром скролле контейнеры ходят по одним и тем же элементам
 * туда-обратно, и высота большинства из них уже измерена. Мерить их заново —
 * обращение в нативный слой ради значения, которое список уже знает.
 *
 * Почему это безопасно: замер пропускается только там, где размер известен и
 * содержимое не менялось. Если высота всё же разойдётся с известной, придёт
 * `onLayout` — геометрия узла изменилась, — и замер выполнится по нему.
 */
export const shouldMeasureOnBind = ({
  keyChanged,
  dataChanged,
  hasKnownSize,
}: IMeasureOnBindParams): boolean => {
  if (dataChanged && !keyChanged) return true;
  if (!keyChanged) return false;

  return !hasKnownSize;
};
