/**
 * Сколько замеров набирает средний размер по типу, прежде чем замереть.
 *
 * Среднее нужно, только чтобы прикинуть высоту ещё не отрисованных строк, и
 * после нескольких десятков замеров точнее оно уже не станет. А вот меняться не
 * перестаёт — и каждое изменение переставляет разом все неизмеренные строки:
 * суммарная высота контента гуляет на сотни пикселей, отведённое строке место
 * расходится с тем, чем она нарисована, и между строками то появляется, то
 * пропадает пустая полоса. Поэтому среднее фиксируется.
 */
const AVERAGE_SAMPLE_LIMIT = 32;

/** Накопленная сумма и число замеров одного типа. */
interface IAverage {
  sum: number;
  count: number;
}

/**
 * Средний измеренный размер по типу элемента.
 *
 * Зачем нужен: оценка высоты строки, до которой отрисовка ещё не дошла. Общая
 * оценка из пропа одна на весь список, а ячейки разнородны — фотография и
 * строка текста отличаются в разы, и общая оценка тянет раскладку и той и
 * другой не туда.
 *
 * Какую проблему решает: держит оценку по каждому типу отдельно и перестаёт её
 * двигать, набрав достаточно замеров, — иначе каждое новое измерение
 * переставляло бы все неизмеренные строки списка разом.
 */
export class TypeSizeAverages {
  private readonly byType = new Map<string, IAverage>();

  /**
   * Учесть замер.
   *
   * @param previous прежний измеренный размер того же элемента; `undefined` —
   * элемент измерен впервые. Повторное измерение правит сумму, но не увеличивает
   * число замеров: это тот же элемент, а не новый образец.
   */
  add(type: string, previous: number | undefined, size: number): void {
    const average = this.byType.get(type) ?? { sum: 0, count: 0 };

    // Набранное среднее больше не трогаем: уточнять его нечем, а переставлять
    // из-за него все неизмеренные строки — значит двигать раскладку впустую.
    if (average.count >= AVERAGE_SAMPLE_LIMIT) return;

    if (previous === undefined) {
      average.sum += size;
      average.count += 1;
    } else {
      average.sum += size - previous;
    }

    this.byType.set(type, average);
  }

  /** Средний размер типа; `undefined` — замеров этого типа ещё не было. */
  get(type: string): number | undefined {
    const average = this.byType.get(type);

    if (average === undefined || average.count === 0) return undefined;

    return average.sum / average.count;
  }
}
