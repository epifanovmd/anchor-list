/**
 * Кэш измеренных размеров, переживающий размонтирование списка.
 *
 * Зачем нужен: измеренные размеры живут в самом списке и умирают вместе с
 * ним. Ушёл с экрана переписки и вернулся — все строки меряются заново, а
 * стартовая позиция доводится несколько кадров по оценкам. Кэш держит
 * размеры снаружи: следующий список над теми же данными знает видимые строки
 * с первого кадра и показывается сразу.
 *
 * Какую проблему решает: адресация ключом. Размер строки от индекса не
 * зависит, поэтому кэш переживает и подгрузку истории, и перезагрузку данных
 * — лишь бы ключи остались теми же. Один кэш можно отдать нескольким спискам
 * над одними данными: они видят замеры друг друга.
 *
 * Чего кэш не знает: что содержимое строки изменилось. Устаревший размер
 * заменяет первый же свежий замер — список рисует строку, узел приходит с
 * другой геометрией, и замер принимается как обычный рост или сжатие. Пока
 * замер не пришёл, строка занимает место по кэшу. Если размеры разом стали
 * другими — сменилась ширина экрана, масштаб шрифта, — кэш стоит очистить.
 *
 * Хранится только измеренное. Объявленные `getFixedItemSize` размеры в кэш не
 * попадают: их задаёт проп, и класть их сюда значило бы держать два источника
 * одной величины.
 */
export class AnchorListSizeCache {
  private readonly sizes = new Map<string, number>();

  /** Сколько строк в кэше. */
  get size(): number {
    return this.sizes.size;
  }

  /** Размер по ключу; `undefined` — строка не измерялась. */
  get(key: string): number | undefined {
    return this.sizes.get(key);
  }

  has(key: string): boolean {
    return this.sizes.has(key);
  }

  /**
   * Положить размер.
   *
   * Список пишет сюда каждый замер сам; вызывать снаружи имеет смысл, чтобы
   * предзаполнить кэш известными размерами — например с сервера.
   */
  set(key: string, size: number): void {
    this.sizes.set(key, size);
  }

  delete(key: string): void {
    this.sizes.delete(key);
  }

  /** Забыть всё: размеры разом стали другими или память дороже. */
  clear(): void {
    this.sizes.clear();
  }
}

/** Создать кэш измерений — один на экран или на данные, вне компонента. */
export const createAnchorListSizeCache = (): AnchorListSizeCache =>
  new AnchorListSizeCache();
