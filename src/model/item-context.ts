import { createContext, useContext } from "react";

/**
 * Ключ элемента, который контейнер рисует прямо сейчас.
 *
 * Зачем нужен: контейнер переживает смену элемента, и при `recycleItems`
 * поддерево ячейки не перемонтируется. Значит, всё, что ячейка хранит в себе,
 * обязано знать, к какому элементу оно относится, — иначе достанется
 * следующему элементу, попавшему в тот же контейнер.
 *
 * Ключ раздаётся контекстом, а не полем `renderItem`: состояние обычно живёт не
 * в корне строки, а в её глубине, и прокидывать ключ пропами пришлось бы
 * вручную через каждый слой.
 *
 * Значением идёт строка, а не объект с ней: контейнер перерисовывается и от
 * смены позиции, а новый объект на каждый такой рендер будил бы всех
 * потребителей контекста впустую.
 */
const ItemKeyContext = createContext<string | null>(null);

/** Раздаёт поддереву ячейки ключ её элемента. */
export const ListItemKeyProvider = ItemKeyContext.Provider;

/** Ключ элемента текущей ячейки; null — узел отрисован вне ячейки списка. */
export const useListItemKey = (): string | null => useContext(ItemKeyContext);
